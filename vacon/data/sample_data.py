def _sample_logs(today: date, leaves: list) -> list:
    """데모용 가상 업무 로그(실제 데이터 아님). (track, 날짜, 팀원, 버전, 업무구분, 완료 Req, 실행 TC, 완료 일감)"""
    rnd = random.Random(7)
    profile = {3: (26, 5, 2.5), 4: (14, 3, 1.5), 5: (24, 5, 3.0), 7: (18, 4, 2.5)}  # 평균 TC, Req, 일감
    off = {(l[1], l[2] + timedelta(days=i)) for l in leaves for i in range((l[3] - l[2]).days + 1)}
    out = []
    for back in range(42, 0, -1):
        day = today - timedelta(days=back)
        if day.weekday() >= 5:
            continue
        ver = "v2.1" if back > 14 else "v2.2"
        for mid, (tc, req, issue) in profile.items():
            if (mid, day) in off:
                continue
            if rnd.random() > 0.12:
                out.append(("dynamic", day, mid, ver, "TC 실행" if rnd.random() < 0.7 else "결과 분석",
                            max(0, round(rnd.gauss(req, 1.2))), max(0, round(rnd.gauss(tc, tc * 0.3))), 0))
            if rnd.random() < 0.55:
                out.append(("req", day, mid, ver, "요구사양서 작성", 0, 0, rnd.randint(1, max(1, round(issue * 1.6)))))
    return out
